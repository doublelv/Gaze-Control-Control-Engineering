function make_test_vectors()
%MAKE_TEST_VECTORS  Regenerate interface/test-vectors/protocol_v1.txt from the
%   MATLAB codec. Run only when the protocol changes on purpose, then make the
%   firmware host tests (firmware/tests) pass against the new file.
here = fileparts(mfilename('fullpath'));
addpath(fullfile(here, '..', 'matlab', 'scripts')); setup_paths();
P = params(); C = proto_const();
L = {};
L{end+1} = '# Protocol v1 test vectors (interface/protocol.md). Synthetic values.';
L{end+1} = '# Generated by tools/make_test_vectors.m. Format: name | KIND | fields | hex bytes';
L{end+1} = '# Both matlab/tests/test_protocol.m and firmware/tests/test_protocol.c must pass on this file.';
cmd = @(d,a,b,led,seq) encode_command(struct('duty',d,'servoUs',[a b],'led',bitget(led,1:4)), seq, P);
L{end+1} = row('cmd_basic',   'CMD', 'duty=6000 servoA=1500 servoB=1600 led=11 seq=1',   cmd(6000,1500,1600,11,1));
L{end+1} = row('cmd_reverse', 'CMD', 'duty=-12000 servoA=500 servoB=2500 led=0 seq=255', cmd(-12000,500,2500,0,255));
L{end+1} = row('cmd_zero',    'CMD', 'duty=0 servoA=1500 servoB=1500 led=15 seq=0',      cmd(0,1500,1500,15,0));
L{end+1} = row('hello',       'HELLO', 'seq=5', encode_simple(C.T_HELLO, 5));
L{end+1} = row('stop',        'STOP',  'seq=9', encode_simple(C.T_STOP, 9));
st = @(cnt,fl,seq,t,rx) encode_state(struct('count',cnt,'flags',fl,'seq',seq,'tUs',t,'rxErrors',rx));
L{end+1} = row('state_basic', 'STATE', 'count=-1234 flags=1 seq=42 t_us=1000000 rx_err=3', st(-1234,1,42,1000000,3));
L{end+1} = row('state_flags', 'STATE', 'count=2147483647 flags=28 seq=200 t_us=4294967295 rx_err=65535', st(2147483647,28,200,4294967295,65535));
L{end+1} = row('hello_reply', 'HELLO_REPLY', 'proto=1 fw_major=1 fw_minor=0 seq=5 t_us=123456', ...
               proto_frame(C.T_HELLO_REPLY, [uint8([1 1 0 5]) typecast(uint32(123456),'uint8')]));
good = st(-1234,1,42,1000000,3);
b1 = good; b1(end) = b1(end) + 1;            L{end+1} = row('bad_checksum', 'BAD', '-', b1);
b2 = good; b2(1) = 171;                      L{end+1} = row('bad_header',   'BAD', '-', b2);
b3 = good(1:end-1);                          L{end+1} = row('bad_short',    'BAD', '-', b3);
b4 = good; b4(4) = 200;                      L{end+1} = row('bad_length',   'BAD', '-', b4);
f = fopen(fullfile(here, '..', 'interface', 'test-vectors', 'protocol_v1.txt'), 'w');
fprintf(f, '%s\n', L{:}); fclose(f);
fprintf('%d lines written\n', numel(L));
end

function s = row(name, kind, fields, bytes)
s = sprintf('%-12s | %-11s | %-66s | %s', name, kind, fields, strtrim(sprintf('%02X ', bytes)));
end
